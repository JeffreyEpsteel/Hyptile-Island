// Writes src/features/voices/Catalog.js from tools/voices/lines.json (the subtitle text of every voiced line).
// usage: node tools/voices/build-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname( fileURLToPath( import.meta.url ) );
const data = JSON.parse( readFileSync( join( here, 'lines.json' ), 'utf8' ) );
const rows = [];
const voices = {};
for ( const b of data.batches ) {

	voices[ b.who ] = voices[ b.who ] || { name: b.name, voice: b.voice, voiceId: b.voiceId };
	for ( const l of b.lines ) rows.push( `\t{ id: ${ JSON.stringify( l.id ) }, who: ${ JSON.stringify( l.who || b.who ) }, kind: ${ JSON.stringify( l.kind ) }, text: ${ JSON.stringify( l.text ) } },` );

}

const src = `// GENERATED by tools/voices/build-catalog.mjs from tools/voices/lines.json: do not edit by hand.
// Every voiced line: { id (file public/audio/voices/<id>.ogg), who (speaker group), kind (the moment it fits), text (subtitle) }.
// Speakers (model ${ data.model }): ${ Object.entries( voices ).map( ( [ k, v ] ) => k + ' = ' + v.voice ).join( ', ' ) }.

export const MODEL = ${ JSON.stringify( data.model ) };

export const SPEAKERS = ${ JSON.stringify( Object.fromEntries( Object.entries( voices ).map( ( [ k, v ] ) => [ k, { name: v.name, voice: v.voice } ] ) ), null, '\t' ) };

export const LINES = [
${ rows.join( '\n' ) }
];
`;
writeFileSync( join( here, '..', '..', 'src', 'features', 'voices', 'Catalog.js' ), src );
console.log( rows.length, 'lines,', Object.keys( voices ).length, 'speakers' );
